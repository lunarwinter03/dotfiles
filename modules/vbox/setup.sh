desktop="$HOME/.local/share/applications/virtualbox.desktop"
marker="# generated by dot (vbox), do not edit"

setup() {
    local src=/usr/share/applications/virtualbox.desktop new
    if (( DRY_RUN )); then item generate "$desktop"; return 0; fi
    [[ -f "$src" ]] || { warn "not found: $src"; return 0; }
    if [[ -e "$desktop" ]] && ! grep -qxF "$marker" "$desktop"; then
        warn "not generated by dot, skipped: $desktop"
        return 0
    fi
    new=$(echo "$marker"; sed "s|^Exec=[^ ]*|Exec=$HOME/.local/bin/VirtualBox|" "$src")
    [[ -f "$desktop" && "$(cat "$desktop")" == "$new" ]] && return 0
    mkdir -p "${desktop%/*}"
    printf '%s\n' "$new" > "$desktop"
    item generated "$desktop"
}

teardown() {
    [[ -f "$desktop" ]] && grep -qxF "$marker" "$desktop" || return 0
    run rm "$desktop"
    item removed "$desktop"
}
